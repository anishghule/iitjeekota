"""Reading data files and writing outputs atomically."""

from __future__ import annotations

import json
from pathlib import Path
from typing import Any

from .errors import BuildError

GENERATED = "Generated by dsapkit ({source}). Do not edit by hand."


def read_json(path: Path, hint: str = "") -> Any:
    if not path.exists():
        raise BuildError(f"missing {path}" + (f": {hint}" if hint else ""))
    try:
        return json.loads(path.read_text(encoding="utf-8"))
    except json.JSONDecodeError as err:
        raise BuildError(f"{path}: invalid JSON at line {err.lineno}: {err.msg}") from err


def reset_dir(path: Path) -> Path:
    """Empty a build's own output folder so no stale file survives a rebuild."""
    if path.exists():
        for child in sorted(path.rglob("*"), reverse=True):
            child.unlink() if child.is_file() or child.is_symlink() else child.rmdir()
    path.mkdir(parents=True, exist_ok=True)
    return path


def write_bytes(path: Path, data: bytes) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    tmp = path.with_name(path.name + ".tmp")
    tmp.write_bytes(data)
    tmp.replace(path)


def write_text(path: Path, text: str) -> None:
    write_bytes(path, text.encode("utf-8"))


def write_json(path: Path, value: Any) -> None:
    write_text(path, json.dumps(value, indent=2, ensure_ascii=False) + "\n")
