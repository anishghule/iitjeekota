"""The headers the site is served with, written from packages/site/security.json, and the checks that keep them strict.

Cloudflare Pages reads a plain-text `_headers` file from the build output: a URL pattern, then
indented `Name: value` lines (at most 100 rules and 2,000 characters a line). `_redirects` makes the
root redirect a real 301, as site.json asks, instead of the page-level refresh Astro writes.
Nothing here is decided per page: one policy for every path, and a noindex rule for the
pages.dev addresses so a preview or the default address is never indexed.
"""

from __future__ import annotations

from datetime import date, datetime, timedelta, timezone
from typing import Any, Mapping

from ..errors import BuildError
from .model import Site

MAX_RULES = 100
MAX_LINE = 2000
KEYWORDS = {"'self'", "'none'"}  # the only quoted source keywords the site's policy may use
REQUIRED_DIRECTIVES = ("default-src", "script-src", "style-src", "object-src", "base-uri", "form-action", "frame-ancestors")
FORBIDDEN = ("'unsafe-inline'", "'unsafe-eval'", "'unsafe-hashes'", "'wasm-unsafe-eval'", "'strict-dynamic'", "*", "data:", "blob:",
             "http:", "https:", "ws:", "wss:", "filesystem:")
REQUIRED_HEADERS = ("X-Content-Type-Options", "Referrer-Policy", "Cross-Origin-Opener-Policy")
REQUIRED_DENIED_FEATURES = ("camera", "microphone", "geolocation")


def _policy(security: Mapping[str, Any]) -> dict[str, list[str]]:
    """The directives as served. The API origin, once there is one, is the only extra place the page may talk to."""
    policy = {name: list(sources) for name, sources in security["csp"].items()}
    if security.get("apiOrigin"):
        policy["connect-src"].append(security["apiOrigin"])
    return policy


def content_security_policy(security: Mapping[str, Any]) -> str:
    return "; ".join(" ".join([name, *sources]) for name, sources in _policy(security).items())


def permissions_policy(security: Mapping[str, Any]) -> str:
    return ", ".join(f"{feature}=()" for feature in security["permissionsPolicy"])


def strict_transport_security(security: Mapping[str, Any]) -> str | None:
    hsts = security["hsts"]
    if not hsts["enabled"]:
        return None
    return "; ".join([f"max-age={hsts['maxAge']}", *(["includeSubDomains"] if hsts["includeSubDomains"] else []),
                      *(["preload"] if hsts["preload"] else [])])


def response_headers(security: Mapping[str, Any]) -> dict[str, str]:
    headers = {"Content-Security-Policy": content_security_policy(security), **security["headers"],
               "Permissions-Policy": permissions_policy(security)}
    hsts = strict_transport_security(security)
    if hsts:
        headers["Strict-Transport-Security"] = hsts
    return headers


def headers_file(security: Mapping[str, Any]) -> str:
    """The `_headers` file: every header for every path, the type of security.txt, then noindex for the pages.dev addresses."""
    out = ["# Generated by dsapkit (packages/site/security.json). Do not edit by hand.", "/*"]
    out += [f"  {name}: {value}" for name, value in response_headers(security).items()]
    out += ["/.well-known/security.txt", "  Content-Type: text/plain; charset=utf-8"]  # RFC 9116 section 3
    for host in security["noindexHosts"]:
        out += [host, "  X-Robots-Tag: noindex"]
    return "\n".join(out) + "\n"


def security_txt(site: Site, security: Mapping[str, Any]) -> str:
    """/.well-known/security.txt (RFC 9116). The contact comes from the facts register, so it is never typed twice."""
    spec = security["securityTxt"]
    contacts = []
    for fact_id in spec["contactFacts"]:
        value, why = site.fact_value(fact_id)
        if why:
            raise BuildError(f"security.txt needs a contact, but {why}")
        contacts.append(f"mailto:{value}")
    lines = [f"Contact: {contact}" for contact in contacts]
    lines += [f"Expires: {spec['expires']}", f"Preferred-Languages: {', '.join(spec['preferredLanguages'])}",
              f"Canonical: {site.origin}/.well-known/security.txt"]
    return "\n".join(lines) + "\n"


def check_security_txt(security: Mapping[str, Any], today: date) -> list[str]:
    """Expires must be an RFC 3339 time that has not passed and is under a year away (RFC 9116 section 2.5.5)."""
    spec = security["securityTxt"]
    try:
        expires = datetime.fromisoformat(spec["expires"])
    except ValueError:
        return [f"securityTxt.expires {spec['expires']!r} is not an RFC 3339 date and time, for example 2027-10-30T00:00:00+05:30"]
    if expires.tzinfo is None:
        return ["securityTxt.expires needs a timezone offset (RFC 3339)"]
    now = datetime(today.year, today.month, today.day, tzinfo=timezone.utc)
    if expires <= now:
        return [f"security.txt expired on {spec['expires']}: renew securityTxt.expires in packages/site/security.json"]
    if expires > now + timedelta(days=365):
        return [f"securityTxt.expires {spec['expires']} is more than a year away; RFC 9116 recommends less than a year"]
    return []


def redirects_file(site: Site) -> str:
    root = site.config["root"]
    return f"# Generated by dsapkit (packages/site/site.json root). Do not edit by hand.\n/ {root['redirectTo']} {root['status']}\n"


def _sources_problems(name: str, sources: list[str]) -> list[str]:
    problems = []
    if "'none'" in sources and len(sources) > 1:
        problems.append(f"csp {name}: 'none' must stand alone")
    for source in sources:
        if source in FORBIDDEN or source.startswith(("http:", "ws:", "*")):
            problems.append(f"csp {name}: {source} is not allowed")
        elif source.startswith("'"):
            if source not in KEYWORDS:
                problems.append(f"csp {name}: {source} is not one of {sorted(KEYWORDS)}")
        elif not source.startswith("https://") or "*" in source:
            problems.append(f"csp {name}: {source!r} must be 'self', 'none' or an exact https origin")
    return problems


def check_security(security: Mapping[str, Any]) -> list[str]:
    """Why this policy is not strict enough (empty when it is)."""
    csp, problems = _policy(security), []  # the policy as served, API origin included
    for name in REQUIRED_DIRECTIVES:
        if name not in csp:
            problems.append(f"csp needs {name}")
    for name, sources in csp.items():
        problems += _sources_problems(name, sources)
    if csp.get("default-src") not in (["'none'"], ["'self'"]):
        problems.append("csp default-src must be 'none' (or 'self')")
    if csp.get("frame-ancestors") != ["'none'"]:
        problems.append("csp frame-ancestors must be 'none': nothing may frame the site")
    if csp.get("object-src") != ["'none'"]:
        problems.append("csp object-src must be 'none'")
    if security.get("apiOrigin") and not security["apiOrigin"].startswith("https://"):
        problems.append("apiOrigin must be an exact https origin")
    for header in REQUIRED_HEADERS:
        if header not in security["headers"]:
            problems.append(f"headers need {header}")
    if security["headers"].get("X-Content-Type-Options") != "nosniff":
        problems.append("X-Content-Type-Options must be nosniff")
    for feature in REQUIRED_DENIED_FEATURES:
        if feature not in security["permissionsPolicy"]:
            problems.append(f"permissionsPolicy must switch off {feature}")
    hsts = security["hsts"]
    if hsts["preload"] and not (hsts["enabled"] and hsts["maxAge"] >= 31536000 and hsts["includeSubDomains"]):
        problems.append("hsts preload needs enabled, maxAge of at least 31536000 (one year) and includeSubDomains (hstspreload.org)")
    text = headers_file(security)
    if sum(1 for line in text.splitlines() if line and not line.startswith((" ", "#"))) > MAX_RULES:
        problems.append(f"more than {MAX_RULES} _headers rules")
    problems += [f"a _headers line is {len(line)} characters; Cloudflare allows {MAX_LINE}" for line in text.splitlines() if len(line) > MAX_LINE]
    return problems


def security_age(security: Mapping[str, Any], today: date) -> int:
    """Days since the header guidance was read; past staleAfterDays it must be read again."""
    age = (today - date.fromisoformat(security["checked"])).days
    if age > security["staleAfterDays"]:
        raise BuildError(f"security.json was read from Cloudflare, MDN and hstspreload.org on {security['checked']}, {age} days ago "
                         f"(limit {security['staleAfterDays']}). Re-read them, update the policy and 'checked'.")
    return age
